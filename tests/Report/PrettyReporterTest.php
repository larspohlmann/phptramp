----------------------------------------------------------------

1 finding (0 errors, 1 warning; limit: 3 hops, warn-limit: 1 hop).

TXT;

        $reporter = new PrettyReporter(
            new Thresholds(3, 1),
            new Paths('/nonexistent-root'),
            false,
            new NullStyler(),
        );

        self::assertSame($expected, $reporter->render([$finding]));
    }

